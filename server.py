def log_marker(marker):
    path = Path(os.environ.get("AVATAR_LOG_FILE", "/var/log/portal/avatar-worker.log"))
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        with path.open("a", encoding="utf-8") as stream:
            stream.write(marker + "\n")
    except OSError:
        # A full/broken log disk must not prevent fatal instance retirement.
        pass
    # Markers carry only stage names, exception classes and numbers. The marker file dies with a self-destroyed machine, so the same
    # line also goes to the container's output (Vast's instance log): the first live boot (2026-11-17) failed without a readable cause.
    print(marker, flush=True)


@dataclass
class Job:
    id: str
    directory: Path
    state: str = "queued"
    progress: float = 0.0
    stage: str = "queued"
    width: int | None = None
    height: int | None = None
    frames: int | None = None
    segments: int | None = None
    gpus: int | None = None
    attention: str | None = None
    compiled: bool | None = None
    exec_s: float | None = None
    error: str | None = None
    finished_at: float | None = None
    file: Path | None = None
    fetching: bool = False
    request: str | None = None

    def public(self):
        result = {"state": self.state, "progress": self.progress, "stage": self.stage, "fps": FPS}
        for key in ("width", "height", "frames", "segments", "gpus", "attention", "compiled", "exec_s", "error"):
            value = getattr(self, key)
            if value is not None:
                result[key] = value
        return result


class JobManager:
    def __init__(self, backend, root, retirement, *, clock=time.monotonic, benchmark_id=None):
        self.backend, self.root, self.retirement, self.clock = backend, Path(root), retirement, clock
        self.root.mkdir(parents=True, exist_ok=True, mode=0o700)
        self.jobs, self.requests = {}, {}
        self.queue = asyncio.Queue()
        self.active = 0
        if benchmark_id:
            if not ID_PATTERN.fullmatch(benchmark_id):
                raise ValueError("invalid benchmark id")
            self.jobs[benchmark_id] = Job(benchmark_id, self.root / benchmark_id, state="failed",
                                          error="readiness probe", finished_at=self.clock())

    def lookup(self, clip):
        self.expire()
        fingerprint = clip.fingerprint()
        if clip.request in self.requests:
            previous, job_id = self.requests[clip.request]
            if previous != fingerprint:
                raise web.HTTPConflict(text='{"error":"conflict"}', content_type="application/json")
            return self.jobs[job_id]
        return None

    def available(self):
        return self.active < 3 and not self.retirement.retiring and self.backend.healthy

    def submit(self, clip, prepared):
        # No await between the second lookup, capacity check and registration.
        existing = self.lookup(clip)
        if existing is not None:
            return existing
        if not self.available():
            return None
        job_id = uuid.uuid4().hex
        directory = self.root / job_id
        spec = {"mode": clip.mode, "prompt": clip.prompt, "size": clip.size, "seed": clip.seed,
                "frames": clip.frames, "segments": clip.segments, "duration": clip.duration, "boxes": clip.boxes}
        (prepared / "job.json").write_text(json.dumps(spec, ensure_ascii=True), encoding="utf-8")
        prepared.rename(directory)
        job = Job(job_id, directory, frames=clip.frames, segments=clip.segments,
                  gpus=getattr(self.backend, "gpus", 1), request=clip.request,
                  **getattr(self.backend, "state", {}))
        self.jobs[job_id] = job
        self.requests[clip.request] = (clip.fingerprint(), job_id)
        self.active += 1
        self.retirement.job_started()
        self.queue.put_nowait((job, spec))
        return job

    def remove(self, job):
        # Direct children generated by us only; never accept a client path.
        if job.directory.parent != self.root or not ID_PATTERN.fullmatch(job.directory.name):
            raise RuntimeError("invalid job directory")
        if job.directory.exists():
            shutil.rmtree(job.directory)
        self.jobs.pop(job.id, None)
        self.requests.pop(job.request, None)

    def expire(self):
        for job in list(self.jobs.values()):
            if not job.fetching and job.finished_at is not None and self.clock() - job.finished_at >= TTL_S:
                self.remove(job)

    async def run(self):
        while True:
            job, spec = await self.queue.get()
            started = self.clock()

            def progress(update):
                for key in ("stage", "gpus", "width", "height", "frames", "attention", "compiled"):
                    if key in update:
                        setattr(job, key, update[key])
                job.progress = max(job.progress, min(1.0, update.get("progress", job.progress)))

            try:
                while not self.backend.healthy:
                    if getattr(self.backend, "dead", False):
                        raise GenerationFailed("generation failed")
                    await asyncio.sleep(.25)
                started = self.clock()
                job.state, job.stage = "running", "loading"
                job.file = await self.backend.render(spec, job.directory, progress)
                job.state, job.progress, job.stage = "done", 1.0, "done"
                job.exec_s = max(0.0, self.clock() - started)
            except asyncio.CancelledError:
                raise
            except GenerationFailed as error:
                job.state, job.stage, job.error = "failed", "failed", str(error)
            except Exception:
                job.state, job.stage, job.error = "failed", "failed", "generation failed"
            finally:
                # Completion from all ranks (or teardown) precedes input removal.
                # If an OS process cannot be killed, retain its directory until retirement.
                if getattr(self.backend, "tree_safe", self.backend.healthy):
                    for path in job.directory.iterdir():
                        if path == job.file:
                            continue
                        if path.is_dir() and not path.is_symlink():
                            shutil.rmtree(path)
                        else:
                            path.unlink()
                job.finished_at = self.clock()
                self.active -= 1
                self.retirement.job_finished()
                self.queue.task_done()
                spec.clear()

    async def sweep(self):
        while True:
            self.expire()
            await asyncio.sleep(15)


def make_app(manager):
    retirement = manager.retirement

    @web.middleware
    async def activity(request, handler):
        # SDK health probes cannot keep a GPU alive indefinitely.
        tracked = request.path != "/health"
        if tracked:
            retirement.request_started()
        try:
            return await handler(request)
        except Invalid as error:
            return web.json_response({"error": "invalid", "detail": str(error)}, status=400)
        except web.HTTPRequestEntityTooLarge:
            return web.json_response({"error": "invalid", "detail": "request exceeds size limit"}, status=400)
        except web.HTTPException:
            raise
        except (ConnectionError, asyncio.CancelledError):
            raise
        except Exception:
            return web.json_response({"error": "invalid", "detail": "request failed"}, status=400)
        finally:
            if tracked:
                retirement.request_finished()

    async def lifecycle(app):
        if hasattr(manager.backend, "start"):
            await manager.backend.start(manager.root.parent)
        tasks = [asyncio.create_task(manager.run()), asyncio.create_task(manager.sweep()),
                 asyncio.create_task(retirement.run())]
        try:
            yield
        finally:
            for task in tasks:
                task.cancel()
            for task in tasks:
                with suppress(asyncio.CancelledError):
                    await task
            if hasattr(manager.backend, "close"):
                await manager.backend.close()
            if getattr(manager.backend, "tree_safe", manager.backend.healthy):
                for job in list(manager.jobs.values()):
                    manager.remove(job)

    async def payload(request):
        try:
            return strict_json(await request.text())
        except UnicodeError:
            raise Invalid("invalid JSON") from None

    # Bound CPU image decoding independently of the generation queue.
    decode_slots = asyncio.Semaphore(2)
    machine = machine_facts()

    async def start(request):
        async with decode_slots:
            body = await payload(request)
            directory = Path(tempfile.mkdtemp(prefix=".validate-", dir=manager.root))
            task = asyncio.create_task(asyncio.to_thread(validate_start, body, directory))
            try:
                try:
                    clip = await asyncio.shield(task)
                except asyncio.CancelledError:
                    with suppress(Exception):
                        await task
                    raise
                job = manager.lookup(clip)
                if job is None and manager.available():
                    job = manager.submit(clip, directory)
            finally:
                if directory.exists():
                    shutil.rmtree(directory)
        if job is None:
            return web.json_response({"error": "busy"}, status=429)
        return web.json_response({"id": job.id, "state": job.state})

    async def find(request):
        job_id = validate_id(await payload(request))
        manager.expire()
        return manager.jobs.get(job_id)

    async def state(request):
        job = await find(request)
        # The machine's own numbers (exam.py) ride on every state answer: the studio keeps its list of machines from them.
        return web.json_response({**job.public(), **({"machine": machine} if machine else {})} if job else {"error": "unknown"},
                                 status=200 if job else 404)

    async def file(request):
        job = await find(request)
        if job is None or job.fetching:
            return web.json_response({"error": "unknown"}, status=404)
        if job.state != "done":
            return web.json_response({"error": "not_ready"}, status=409)
        if job.file is None or not job.file.is_file():
            manager.remove(job)
            return web.json_response({"error": "unknown"}, status=404)
        job.fetching = True
        try:
            response = web.StreamResponse(headers={"Content-Type": "video/mp4",
                                                   "Content-Length": str(job.file.stat().st_size)})
            await response.prepare(request)
            with job.file.open("rb") as source:
                while chunk := source.read(1024 * 1024):
                    await response.write(chunk)
            await response.write_eof()
            return response
        finally:
            job.fetching = False

    async def health(request):
        healthy = manager.backend.healthy and not retirement.retiring
        return web.json_response({"status": "ready" if healthy else "unavailable"}, status=200 if healthy else 503)

    app = web.Application(client_max_size=MAX_BODY_BYTES, middlewares=[activity])
    app.cleanup_ctx.append(lifecycle)
    app.router.add_post("/clip/start", start)
    app.router.add_post("/clip/state", state)
    app.router.add_post("/clip/file", file)
    app.router.add_get("/health", health)
    return app


async def serve():
    runner = backend = None
    # Startup now loads resident models. SIGTERM must cancel that await too,
    # otherwise the launcher can outlive a server stopped before ready.
    if os.name != "nt":
        loop = asyncio.get_running_loop()
        task = asyncio.current_task()
        for signum in (signal.SIGTERM, signal.SIGINT):
            loop.add_signal_handler(signum, task.cancel)
    try:
        async def request_retirement():
            Path(os.environ["AVATAR_RETIRE_FILE"]).touch(mode=0o600)
            await asyncio.Event().wait()

        retirement = IdleRetirement(log_marker, request_retirement=request_retirement)
        backend = EngineBackend()
        manager = JobManager(backend, os.environ["AVATAR_JOB_ROOT"], retirement,
                             benchmark_id=os.environ.get("AVATAR_BENCHMARK_ID"))
        runner = web.AppRunner(make_app(manager), access_log=None)
        await runner.setup()
        await web.TCPSite(runner, "127.0.0.1", 18001).start()
        await backend.failed.wait()
        # Publish failure for every accepted job before the parent retires us.
        await manager.queue.join()
        raise GenerationFailed("generation failed")
    except asyncio.CancelledError:
        pass
    except Exception as error:
        log_marker(f"AVATAR_FATAL server {type(error).__name__}")
        raise SystemExit(1) from None
    finally:
        try:
            if runner is not None:
                await runner.cleanup()
        finally:
            if backend is not None:
                await backend.close()


if __name__ == "__main__":
    asyncio.run(serve())
